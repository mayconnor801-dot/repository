let currentLang = 'es';

document.addEventListener('DOMContentLoaded', () => {
    // 1. LÓGICA DE CAMBIO DE IDIOMA
    const langToggleBtn = document.getElementById('lang-toggle');
    const langText = document.getElementById('lang-text');

    if (langToggleBtn) {
        langToggleBtn.addEventListener('click', () => {
            currentLang = currentLang === 'es' ? 'en' : 'es';
            langText.textContent = currentLang === 'es' ? 'EN' : 'ES';
            updateLanguage(currentLang);
        });
    }

    function updateLanguage(lang) {
        // Actualizar textos normales
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[lang][key]) {
                element.textContent = translations[lang][key];
            }
        });

        // Actualizar Placeholders de los formularios
        document.querySelectorAll('[data-i18n-ph]').forEach(element => {
            const key = element.getAttribute('data-i18n-ph');
            if (translations[lang][key]) {
                element.setAttribute('placeholder', translations[lang][key]);
            }
        });

        // Cambiar lang atribut de la etiqueta HTML
        document.documentElement.lang = lang;
    }

    // 2. CARRUSEL DE TESTIMONIOS
    const cards = document.querySelectorAll('.testimonial-card');
    let currentIndex = 0;

    if (cards.length > 1) {
        setInterval(() => {
            cards[currentIndex].classList.remove('active');
            currentIndex = (currentIndex + 1) % cards.length;
            cards[currentIndex].classList.add('active');
        }, 3500);
    }
});